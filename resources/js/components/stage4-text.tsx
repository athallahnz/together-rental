export type Stage4Key = Extract<MessageKey, `stage4.ui.${string}`>;

/** Strict typed translations for operational UI. Never pass the result as API/DB values. */
export function stage4Translate(
    key: Stage4Key,
    locale: AppLocale = getEffectiveLocale(),
): string {
    return translateKey(key, locale);
}

/** Date-time formatter for operational display. Date-only values are never converted to a different day. */
export function stage4FormatDateTime(
    value: Date | string | number | null | undefined,
    locale: AppLocale = getEffectiveLocale(),
): string {
    if (value === null || value === undefined || value === '') {
        return '—';
    }

    const date = value instanceof Date ? value : new Date(value);

    if (Number.isNaN(date.getTime())) {
        return '—';
    }

    return new Intl.DateTimeFormat(locale === 'en' ? 'en-GB' : 'id-ID', {
        dateStyle: 'medium',
        timeStyle: 'short',
        timeZone: 'Asia/Jakarta',
    }).format(date);
}

