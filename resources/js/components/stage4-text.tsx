/** Format item counts with spacing and correct English singular/plural forms. */
export function stage4ItemCount(
    count: number,
    locale: AppLocale = getEffectiveLocale(),
): string {
    return `${count} ${stage4Translate(locale === 'en' && count !== 1 ? 'stage4.ui.a0092d833542' : 'stage4.ui.3a7d9767b123', locale)}`;
}

/** Render-only mapping for existing status dictionaries, preserving original codes in form payloads. */
export function stage4TranslateDynamic(
    value: string | undefined | null,
    locale: AppLocale = getEffectiveLocale(),
): string {
    if (!value) {
        return '—';
    }

    const key =
        stage4RawDisplayKeys[value.toLowerCase()] ?? displayLabels[value];

    return key ? stage4Translate(key, locale) : value;
}

export function Stage4Text({ k }: { k: Stage4Key }) {
    const { props } = usePage();
    const locale: AppLocale =
        (props as { locale?: string }).locale === 'en' ? 'en' : 'id';

    return stage4Translate(k, locale);
}
